import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const routes = readFileSync(new URL('./routes-v13.js', import.meta.url), 'utf8');
const html = readFileSync(new URL('./index.html', import.meta.url), 'utf8');
const shell = readFileSync(new URL('./h2c-shell.js', import.meta.url), 'utf8');
const help = readFileSync(new URL('./help-kb.js', import.meta.url), 'utf8');
const store = readFileSync(new URL('./session-store.js', import.meta.url), 'utf8');

test('live defect fixes stay in the page source', () => {
  assert.equal(html.includes('opensourced'), false);
  assert.equal(routes.includes('opensourced'), false);
  assert.match(html, /Open-source, AI-aided Apollo RealityCharting/);
  assert.match(routes, /Open-source, AI-aided Apollo RealityCharting/);
  assert.doesNotMatch(html, /#realitychart svg\{min-height:560px/);
  assert.match(routes, /setPointerCapture\?\.\(e\.pointerId\)/);
  assert.match(routes, /function reportGaps/);
  assert.match(routes, /Cost \/ ROI does not block the report/);
  assert.match(routes, /function moneyText/);
  assert.match(routes, /function clock24/);
  assert.match(routes, /function causeSetVerified/);
  assert.match(routes, /function applyCauseSetVerified/);
  assert.match(routes, /children:i\?`And`:`Or`/);
  assert.match(routes, /e\.children\.every\(e=>e\.node\.verified\)/);
  assert.match(routes, /function formatIntegrity/);
  assert.match(routes, /This is not a root-cause declaration/);
  assert.match(routes, /knownIds:/);
  assert.match(routes, /Lead investigator/);
  assert.doesNotMatch(routes, /children:`Contact`/);
  assert.match(routes, /Add another primary effect/);
  assert.match(routes, /A reload keeps this draft/);
  assert.match(routes, /metaKey/);
  assert.match(routes, /h2c-cards h2c-ca/);
  assert.match(routes, /h2c-cards h2c-ai/);
  assert.doesNotMatch(routes, /sm:grid-cols-\[1fr_9rem/);
  assert.match(routes, /Labelled as a hypothesis, not a finding/);
  assert.match(routes, /RCA Coach — final check/);
  assert.doesNotMatch(routes, /RC Coach/);
  assert.equal(routes.includes('localStorage'), false);
  assert.match(shell, /const expectedCards = !audit \? 0/);
  assert.match(shell, /name: 'Evidence'/);
  assert.match(shell, /name: 'Chart'/);
  assert.ok(shell.indexOf("name: 'Evidence'") < shell.indexOf("name: 'Chart'"));
  assert.match(shell, /Location required \(facility, unit, equipment\)/);
  assert.doesNotMatch(shell, /Location recommended/);
  assert.doesNotMatch(routes, /md:grid-cols-3`,children:\[\(0,B\.jsxs\)\(`label`,\{className:`text-sm`,children:\[`Layer`/);
  assert.match(help, /3 Record each observation/);
  assert.match(help, /4 Generate RealityChart/);
  assert.match(store, /sessionStorage/);
  assert.doesNotMatch(html, /http:\/\/\[::1\]:\*/);
});
